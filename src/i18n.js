  let language = 'tr';

  function setLanguage(code) {
    language = code === 'en' ? 'en' : 'tr';
    return language;
  }

  function getLanguage() {
    return language;
  }

  // Sistem dilinden varsayılan: Türkçe sistemlerde Türkçe, diğerlerinde İngilizce.
  function languageForLocale(locale) {
    return String(locale || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
  }

  const SEPARATORS = [' · ', ' • ', '; ', ' — '];

  function translateCore(text, depth = 0) {
    if (Object.prototype.hasOwnProperty.call(EN, text)) return EN[text];
    for (const [pattern, replacement] of EN_PATTERNS) {
      const match = text.match(pattern);
      if (!match) continue;
      return typeof replacement === 'function'
        ? replacement(match, (part) => translateCore(part, depth + 1))
        : text.replace(pattern, replacement);
    }
    if (depth > 2) return null;
    for (const separator of SEPARATORS) {
      if (!text.includes(separator)) continue;
      const parts = text.split(separator);
      const translated = parts.map((part) => translateCore(part.trim(), depth + 1) ?? part);
      if (translated.some((part, index) => part !== parts[index])) return translated.join(separator);
    }
    // Birden çok cümle: her cümle ayrı çevrilir.
    const sentences = text.split(/(?<=[.!?…])\s+(?=[A-ZÇĞİÖŞÜ0-9"“(])/);
    if (sentences.length > 1) {
      const translated = sentences.map((sentence) => translateCore(sentence, depth + 1) ?? sentence);
      if (translated.some((sentence, index) => sentence !== sentences[index])) return translated.join(' ');
    }
    return null;
  }

  // Metni etkin dile çevirir; çevirisi yoksa olduğu gibi döndürür. Baştaki ve
  // sondaki boşluklar korunur (HTML metin düğümleri için).
  function translate(text) {
    if (language === 'tr' || typeof text !== 'string') return text;
    const trimmed = text.trim();
    if (!trimmed) return text;
    const result = translateCore(trimmed.replace(/\s+/g, ' '));
    if (result === null || result === undefined) return text;
    const lead = text.match(/^\s*/)[0];
    const trail = text.match(/\s*$/)[0];
    return lead + result + trail;
  }

  // Kodda doğrudan kullanım: t('Metin') veya t('{n} dosya', { n: 3 }).
  function t(text, vars) {
    let result = translate(text);
    if (vars) result = result.replace(/\{(\w+)\}/g, (all, key) => (key in vars ? String(vars[key]) : all));
    return result;
  }

  // ── Tarayıcı tarafı: belge ve sonradan eklenen öğelerin çevirisi ──
  const ATTRIBUTES = ['title', 'placeholder', 'aria-label', 'label'];
  // Kullanıcı içeriği: dosya adları, klasör yolları ve yazılan metinler.
  const SKIP_SELECTOR = [
    '[data-i18n-skip]', '.text-overlay', '.text-layer-label', 'script', 'style', 'textarea',
    '.gif-seq-name', '.batch-item-name', '.folder-btn span', '#exportDoneDesc',
    '#videoFileName', '#photoFileName', '#gifClipName',
  ].join(', ');

  function shouldSkip(node) {
    const element = node.nodeType === 1 ? node : node.parentElement;
    return !element || Boolean(element.closest(SKIP_SELECTOR));
  }

  function translateTextNode(node) {
    if (shouldSkip(node)) return;
    const next = translate(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  }

  function translateAttributes(element) {
    if (element.closest(SKIP_SELECTOR)) return;
    for (const name of ATTRIBUTES) {
      const value = element.getAttribute(name);
      if (!value) continue;
      const next = translate(value);
      if (next !== value) element.setAttribute(name, next);
    }
  }

  function translateTree(rootNode) {
    if (!rootNode || language === 'tr') return;
    if (rootNode.nodeType === 3) {
      translateTextNode(rootNode);
      return;
    }
    if (rootNode.nodeType !== 1) return;
    translateAttributes(rootNode);
    const walker = rootNode.ownerDocument.createTreeWalker(rootNode, 1 | 4);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === 3) translateTextNode(node);
      else translateAttributes(node);
      node = walker.nextNode();
    }
  }

  // Belgeyi bir kez çevirir ve sonraki değişiklikleri (bildirimler, durum
  // metinleri, ana süreçten gelen hatalar) izler. Türkçede hiçbir şey yapmaz.
  function observeDocument(doc) {
    if (language === 'tr' || !doc || !doc.body) return null;
    doc.documentElement.lang = language;
    translateTree(doc.body);
    doc.title = translate(doc.title);
    const observer = new doc.defaultView.MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') translateTextNode(mutation.target);
        else if (mutation.type === 'attributes') translateAttributes(mutation.target);
        else mutation.addedNodes.forEach((node) => translateTree(node));
      }
    });
    observer.observe(doc.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRIBUTES,
    });
    return observer;
  }

